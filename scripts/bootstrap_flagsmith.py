#!/usr/bin/env python3
"""Bootstrap a fresh self-hosted Flagsmith for the DoNotMix demo (local / Docker only).

1. waits for the API, 2. signs up (or logs in) a local admin with generated credentials,
3. creates the organisation and a Master API key, 4. writes them to an env file,
5. seeds the MixMart project with the official Flagsmith CLI (scripts/seed_mixmart.sh).

Never point this at a shared or production Flagsmith. Credentials are random, local and
written only to --env-file (default .env, git-ignored).
"""

from __future__ import annotations

import argparse
import json
import os
import secrets
import subprocess
import sys
import time
import urllib.error
import urllib.request
from pathlib import Path
from urllib.parse import urlparse

HERE = Path(__file__).resolve().parent


def call(base: str, method: str, path: str, body=None, token: str | None = None):
    req = urllib.request.Request(base.rstrip("/") + path, method=method, data=json.dumps(body).encode() if body is not None else None)
    req.add_header("Content-Type", "application/json")
    if token:
        req.add_header("Authorization", f"Token {token}")
    try:
        with urllib.request.urlopen(req, timeout=15) as r:
            raw = r.read()
            return r.status, (json.loads(raw) if raw else None)
    except urllib.error.HTTPError as e:
        return e.code, json.loads(e.read() or b"null")


def read_env(path: Path) -> dict:
    out = {}
    if path.exists():
        for line in path.read_text().splitlines():
            if "=" in line and not line.lstrip().startswith("#"):
                k, v = line.split("=", 1)
                out[k.strip()] = v.strip()
    return out


def host_key_var(api_url: str) -> str:
    u = urlparse(api_url)
    host = (u.hostname or "").replace("_", "__").replace("-", "__").replace(".", "_")
    return f"FLAGSMITH_API_KEY_{host}_{u.port}" if u.port else f"FLAGSMITH_API_KEY_{host}"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--api-url", default=os.environ.get("FLAGSMITH_API_URL", "http://localhost:8000"))
    ap.add_argument("--env-file", default=".env")
    ap.add_argument("--org", default="DoNotMix Demo")
    ap.add_argument("--no-seed", action="store_true")
    ap.add_argument("--timeout", type=int, default=240)
    a = ap.parse_args()
    base = a.api_url.rstrip("/")
    host = urlparse(base).hostname or ""
    if host not in ("localhost", "127.0.0.1", "flagsmith", "::1") and not host.endswith((".localhost", ".test")):
        print(f"refusing to bootstrap non-local Flagsmith at {base}", file=sys.stderr)
        return 3
    t0 = time.time()
    while True:
        try:
            with urllib.request.urlopen(base + "/health/liveness/", timeout=5) as r:
                if r.status == 200:
                    break
        except Exception:
            pass
        if time.time() - t0 > a.timeout:
            print("Flagsmith did not become healthy in time", file=sys.stderr)
            return 4
        time.sleep(3)
    envp = Path(a.env_file)
    env = read_env(envp)
    keyvar = host_key_var(base)
    if env.get(keyvar):
        print(f"{envp} already has {keyvar}; skipping account bootstrap")
    else:
        email = env.get("FLAGSMITH_LOCAL_ADMIN_EMAIL") or "admin@donotmix.test"
        pw = env.get("FLAGSMITH_LOCAL_ADMIN_PASSWORD") or secrets.token_urlsafe(18)
        code, _ = call(base, "POST", "/api/v1/auth/users/", {"email": email, "password": pw, "first_name": "Local", "last_name": "Admin", "sign_up_type": "NO_INVITE"})
        code, res = call(base, "POST", "/api/v1/auth/login/", {"email": email, "password": pw})
        if code != 200:
            print(f"login failed ({code}): {res}. If {email} exists with another password, set FLAGSMITH_LOCAL_ADMIN_PASSWORD in {envp}.", file=sys.stderr)
            return 4
        token = res["key"]
        _, orgs = call(base, "GET", "/api/v1/organisations/", token=token)
        org = next((o for o in (orgs or {}).get("results", []) if o["name"] == a.org), None)
        if not org:
            _, org = call(base, "POST", "/api/v1/organisations/", {"name": a.org}, token=token)
        code, key = call(base, "POST", f"/api/v1/organisations/{org['id']}/master-api-keys/", {"name": "donotmix-local", "is_admin": True}, token=token)
        if code not in (200, 201):
            print(f"could not create Master API key: {key}", file=sys.stderr)
            return 4
        lines = envp.read_text().splitlines() if envp.exists() else ["# generated by scripts/bootstrap_flagsmith.py (local demo only, never commit)"]
        lines = [l for l in lines if not l.startswith(("FLAGSMITH_LOCAL_ADMIN_", "FLAGSMITH_API_URL=", keyvar + "="))]
        lines += [f"FLAGSMITH_LOCAL_ADMIN_EMAIL={email}", f"FLAGSMITH_LOCAL_ADMIN_PASSWORD={pw}", f"FLAGSMITH_API_URL={base}", f"{keyvar}={key['key']}"]
        envp.write_text("\n".join(lines) + "\n")
        os.chmod(envp, 0o600)
        env = read_env(envp)
        print(f"bootstrapped organisation '{a.org}' and wrote credentials to {envp}")
    if a.no_seed:
        return 0
    child = dict(os.environ, FLAGSMITH_API_URL=base, **{keyvar: env[keyvar]}, FLAGSMITH_ORGANISATION=a.org)
    return subprocess.call(["bash", str(HERE / "seed_mixmart.sh")], env=child)


if __name__ == "__main__":
    raise SystemExit(main())

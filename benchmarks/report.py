"""Render docs/BENCHMARKS.md from measured results (never hand-edit the numbers).

    python -m benchmarks.report
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def pct(x):
    return "n/a" if x is None else f"{100 * x:.0f}%"


def f2(x):
    return "n/a" if x is None else f"{x:.2f}"


def main() -> int:
    s = json.loads((ROOT / "benchmarks/results/latest/summary.json").read_text())
    mm_p = ROOT / "benchmarks/results/mixmart/summary.json"
    mm = json.loads(mm_p.read_text()) if mm_p.exists() else None
    sk_p = ROOT / "benchmarks/results/skill_eval/summary.json"
    sk = json.loads(sk_p.read_text()) if sk_p.exists() else None
    src = (ROOT / "benchmarks/results/latest/SOURCE").read_text().strip() if (ROOT / "benchmarks/results/latest/SOURCE").exists() else "?"
    L = ["# DoNotMix benchmark results", "",
         "_Generated by `python -m benchmarks.report` from measured data. Do not edit numbers by hand._", "",
         f"- Synthetic suite: `{s['command']}` at commit `{s['git_commit']}`, {s['created_at']}, {s['seconds']}s on {s['machine']['platform']} ({s['machine']['cpus']} CPUs), raw rows: `{src}/raw.jsonl`",
         f"- Evaluation split: {s['config']['eval_seeds_used']} cases per size (seeds 100+); development seeds (0-{s['config']['dev_seeds'] - 1}) excluded from these tables. Random baselines: {s['config']['random_seeds']} seeds per case.",
         "- Each case: random constraints, planted 2/3/4-way faults (25% of literals require a flag OFF), faults can mask each other in shared tests, and generated source code where a fault's flags share a function with probability `colocate` (decoy functions share flags harmlessly). The engine never sees the faults.", ""]
    L += ["## Hypotheses", "", "| | Hypothesis | Result | Evidence |", "|---|---|---|---|"]
    for h in s["hypotheses"]:
        L.append(f"| {h['id']} | {h['statement']} | **{h['result']}** | {h['evidence']} |")
    L += ["", "## E1 - Same test budget, different strategies", "",
          "B2 = size of the greedy pairwise suite, B3 = size of the greedy 3-way suite. `detected` = share of planted faults exposed; NAPFD = normalized average percentage of faults detected (Qu et al. 2007; higher = earlier); `first` = tests until the first failure.", ""]
    for bl in ("B2", "B3"):
        L += [f"### Budget {bl}", "", "| flags | colocate | budget | strategy | detected | 2-way | 3-way | 4-way | NAPFD | first |", "|---|---|---|---|---|---|---|---|---|---|"]
        for r in [r for r in s["fixed_budget"] if r["budget_label"] == bl]:
            o = r["detection_by_order"]
            L.append(f"| {r['n']} | {r['colocate']} | {r['budget']:.1f} | {r['strategy']} | {pct(r['detected_mean'])} ± {pct(r['detected_std'])} | {pct(o.get('2'))} | {pct(o.get('3'))} | {pct(o.get('4'))} | {f2(r['apfd_mean'])} | {f2(r['first_failure_mean'])} |")
        L.append("")
    L += ["`risk:code-only` disables the change-from-live prior; `risk:change-only` disables the static-analysis prior. With `colocate=0.0` the code gives no signal by construction.", "",
          "## E2 - Cost to reach full t-way coverage", "", "| flags | t | strategy | tests (mean ± sd) |", "|---|---|---|---|"]
    for r in s["coverage_cost"]:
        label = "exhaustive (feasible configurations, counted not executed)" if r["strategy"] == "exhaustive" else r["strategy"]
        L.append(f"| {r['n']} | {r['t'] or '-'} | {label} | {r['tests_mean']:.1f} ± {r['tests_std']:.1f} |")
    L += ["", "## E3 - Counterexample minimization (full DoNotMix pipeline)", "",
          "| flags | colocate | hazards | exact | exact incl. constraint-implied | over | under | false positive | core size | true size | raw counterexample diff | extra tests |",
          "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for m in s["minimization"]:
        L.append(f"| {m['n']} | {m['colocate']} | {m['count']} | {pct(m['exact_rate'])} | {pct(m.get('exact_or_implied_rate'))} | {pct(m['overspecified_rate'])} | {pct(m['underspecified_rate'])} | {pct(m['false_positive_rate'])} | {m['core_size_mean']} | {m['true_size_mean']} | {m['raw_counterexample_diff_mean']} | {m['extra_tests_mean']} |")
    if mm:
        L += ["", "## E4 - MixMart (real app, real pytest runs, live Flagsmith snapshot)", "",
              f"- Flagsmith: {mm['flagsmith']['environment']} at {mm['flagsmith']['api_url']} (source: {mm['flagsmith']['source']}), {mm['flags']} flags, personas {mm['personas']}",
              f"- Exhaustive reference: {mm['feasible_configs']} feasible of {mm['total_configs']} states, {mm['exhaustive_executions']} executions, {mm['exhaustive_seconds']}s; planted bugs exposed: {len(mm['bugs_exposed_by_exhaustive'])}/{mm['planted_bugs']}", "",
              "| budget | strategy | planted bugs exposed | tests to first failure |", "|---|---|---|---|"]
        for r in mm["strategies"]:
            found = r.get("bugs_found", r.get("bugs_found_mean"))
            first = r.get("first_failure", r.get("first_failure_mean"))
            L.append(f"| {r['budget_label']} ({r['budget']}) | {r['strategy']}{' (10 seeds, mean)' if r['strategy'] == 'random' else ''} | {found}/{mm['planted_bugs']} | {first} |")
        sc = mm["scan"]
        L += ["", f"Full `donotmix scan` (risk, t=3): {sc['configs']} configurations, {sc['executions_total']} executions incl. minimization, {sc['seconds']}s, 2-way {pct(sc['coverage']['2']['ratio'])} / 3-way {pct(sc['coverage']['3']['ratio'])} coverage. Planted bugs matched by minimized hazards: {len(sc['bugs_matched'])}/{mm['planted_bugs']}.", "",
              "| hazard | status | core | personas | tests | generality | ground truth |", "|---|---|---|---|---|---|---|"]
        for h in sc["hazards"]:
            core = ", ".join(f"{k}={'on' if v else 'off'}" for k, v in h["core"].items())
            L.append(f"| {h['hazard']} | {h['status']} | {core} | {', '.join(h['personas'])} | {', '.join(h['tests'])} | {h['generality']} | {h['matches'] or '-'}{' (' + h['match'] + ')' if h.get('match') and h['match'] != 'exact' else ''} |")
    L += ["", "## E5 - Agent Skill token efficiency", ""]
    if sk:
        L += [sk.get("markdown", json.dumps(sk, indent=1))]
    else:
        L += ["Not run yet (`python benchmarks/skill_eval.py`)."]
    L += ["", "## Threats to validity", "",
          "- Synthetic faults are boolean conjunctions; real interaction bugs can depend on values, timing or data.",
          "- The change-from-live prior assumes faults involve changed flags; the generator draws ON-literals 75% of the time while baselines are ~35% ON, which favors that prior. The `risk:change-only` ablation makes this visible.",
          "- MixMart is a single, small app with bugs planted by the authors; it demonstrates the workflow end-to-end rather than proving general effectiveness.",
          "- Finite testing never proves safety: a clean DoNotMix run means no failure was observed for the tested states, personas and tests.", ""]
    out = ROOT / "docs" / "BENCHMARKS.md"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(L))
    print(f"wrote {out.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
